#!/usr/bin/env python3
"""Generate the compact ROM database header + mapper coverage report.

Input : data/MesenNesDB.txt  (Mesen game database; CRC32 over PRG+CHR)
Output: src/core/romdb_gen.h   (sorted CRC table, binary-searched at runtime)
        docs/03_mapper_coverage.md (mapper census of licensed / Famicom titles)

Selection rule for "official" titles: an entry is kept when its board name is
known (NesCartDB only catalogues physical, i.e. officially produced, carts)
or when the system is "Famicom". Entries flagged VS/PlayChoice/VT are dropped.
"""
import sys, os, collections, datetime

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC  = os.path.join(ROOT, 'data', 'MesenNesDB.txt')
OUT_H = os.path.join(ROOT, 'src', 'core', 'romdb_gen.h')
OUT_MD = os.path.join(ROOT, 'docs', '03_mapper_coverage.md')

# Mapper ids implemented by the firmware: read from the registry in src/core/mapper.c
import re as _re
IMPLEMENTED = {int(x) for x in _re.findall(r'M\((\d+)\)', open(os.path.join(ROOT, 'src', 'core', 'mapper.c')).read())}

def I(x):
    x = x.strip()
    return int(x) if x else 0

def load():
    rows = []
    with open(SRC, encoding='utf-8', errors='replace') as f:
        for line in f:
            if line.startswith('#') or not line.strip():
                continue
            p = line.rstrip('\n').split(',')
            if len(p) < 18:
                continue
            rows.append(p)
    return rows

MIRROR = {'h': 0, 'v': 1, '4': 2, '': 0, 'a': 3, 'b': 3}

def main():
    rows = load()
    keep = []
    for r in rows:
        crc, system, board, pcb, chip, mapper = r[0], r[1], r[2], r[3], r[4], I(r[5])
        if system not in ('NesNtsc', 'NesPal', 'Famicom'):
            continue
        if not board and system != 'Famicom':
            continue
        if mapper > 4095:
            continue
        keep.append(r)
    # dedupe by CRC (first wins)
    seen = set(); uniq = []
    for r in keep:
        c = int(r[0], 16)
        if c in seen: continue
        seen.add(c); uniq.append(r)
    uniq.sort(key=lambda r: int(r[0], 16))

    with open(OUT_H, 'w') as h:
        h.write('/* AUTO-GENERATED by tools/gen_romdb.py -- do not edit.\n')
        h.write(' * Source: Mesen game database (NesCartDB + NES 2.0 header DB).\n')
        h.write(' * CRC32 is computed over PRG-ROM followed by CHR-ROM (no header).\n */\n')
        h.write('#pragma once\n#include <stdint.h>\n\n')
        h.write('#define ROMDB_FLAG_BATTERY     0x04\n#define ROMDB_FLAG_BUSCONFLICT 0x08\n')
        h.write('#define ROMDB_MIRROR(f) ((f) & 3)  /* 0=H 1=V 2=4screen 3=single */\n\n')
        h.write('typedef struct {\n  uint32_t crc;\n  uint16_t mapper;\n  uint8_t  submapper;\n  uint8_t  flags;\n')
        h.write('  uint16_t prg_kb;\n  uint16_t chr_kb;\n  uint8_t  chrram_kb;\n  uint8_t  wram_kb;\n  uint8_t  sram_kb;\n  uint8_t  system; /* 0=NTSC 1=PAL 2=Famicom */\n} romdb_entry_t;\n\n')
        h.write('#define ROMDB_COUNT %d\n\n' % len(uniq))
        h.write('static const romdb_entry_t romdb_table[ROMDB_COUNT] = {\n')
        for r in uniq:
            crc = int(r[0], 16)
            sysid = {'NesNtsc': 0, 'NesPal': 1, 'Famicom': 2}[r[1]]
            flags = MIRROR.get(r[12], 0)
            if r[11] == '1': flags |= 0x04
            if r[14].strip() == '1': flags |= 0x08
            h.write('  {0x%08X,%d,%d,%d,%d,%d,%d,%d,%d,%d},\n' % (
                crc, I(r[5]), I(r[15]), flags, min(I(r[6]), 65535), min(I(r[7]), 65535),
                min(I(r[8]), 255), min(I(r[9]), 255), min(I(r[10]), 255), sysid))
        h.write('};\n')

    # ---- coverage report ---------------------------------------------------
    lic = [r for r in rows if r[2] and r[1] in ('NesNtsc', 'NesPal', 'Famicom')]
    mc = collections.Counter(); boards = collections.defaultdict(set); chips = collections.defaultdict(set)
    subs = collections.defaultdict(set); fc = collections.Counter()
    for r in lic:
        m = I(r[5]); mc[m] += 1; boards[m].add(r[2]); subs[m].add(r[15].strip() or '0')
        if r[4]: chips[m].add(r[4])
        if r[1] == 'Famicom': fc[m] += 1
    total = len(lic)
    covered = sum(c for m, c in mc.items() if m in IMPLEMENTED)
    with open(OUT_MD, 'w') as md:
        md.write('# マッパー集計（公式・ライセンス品 = 基板名が判明しているカートリッジ）\n\n')
        md.write('生成: %s / 入力: Mesen NES DB（NesCartDB 2017-08-21 + NES 2.0 ヘッダ DB 2021-12-25 由来）\n\n' % datetime.date.today())
        md.write('- 対象タイトル数: **%d**（NTSC %d / PAL %d / Famicom %d）\n' % (
            total, sum(1 for r in lic if r[1] == 'NesNtsc'), sum(1 for r in lic if r[1] == 'NesPal'),
            sum(1 for r in lic if r[1] == 'Famicom')))
        md.write('- 出現マッパー種類: **%d**\n' % len(mc))
        md.write('- ファームウェア実装済みマッパーでカバーされるタイトル: **%d / %d (%.2f%%)**\n\n' % (covered, total, 100.0 * covered / total))
        md.write('| 実装 | Mapper | 本数 | 累積% | うちFC | サブマッパー | 代表チップ | 代表基板 |\n|---|---:|---:|---:|---:|---|---|---|\n')
        acc = 0
        for m, c in sorted(mc.items(), key=lambda x: -x[1]):
            acc += c
            md.write('| %s | %d | %d | %.1f | %d | %s | %s | %s |\n' % (
                '✅' if m in IMPLEMENTED else '—', m, c, 100.0 * acc / total, fc[m],
                ' '.join(sorted(subs[m])), ', '.join(sorted(chips[m])[:4]), ', '.join(sorted(boards[m])[:4])))
        md.write('\n> 「—」は未実装（海賊版マルチカート BMC-*、UNL-*、Game Genie 等の非ライセンス基板が中心）。\n')
        # ---- how to read the table, and what "implemented" does not cover (2026-11 coverage review)
        fam = [r for r in lic if r[1] == 'Famicom']
        fam_unreg = sum(1 for r in fam if I(r[5]) not in IMPLEMENTED)
        fam_batt = sum(1 for r in fam if r[11].strip() == '1')
        fam_prg512 = sum(1 for r in fam if I(r[6]) >= 512); fam_chr512 = sum(1 for r in fam if I(r[7]) >= 512)
        fam_speech = sum(1 for r in fam if any(k in r[4] for k in ('D7756C', 'D7755C', 'M50805')))
        fam_noboard = sum(1 for r in rows if r[1] == 'Famicom' and not r[2])
        md.write('\n## この表の読み方\n\n')
        md.write('- 単位は DB の行（ダンプ・版ごとに 1 行）で、タイトルの数ではない。NES（NTSC・PAL）の行と、基板名のある非ライセンス基板（COLORDREAMS、AVE、TENGEN、CAMERICA など）も含む。\n')
        md.write('- 「実装」は、そのマッパー番号がファームに登録されているという意味。基板の全機能が動くことまでは示さない（下の表）。\n')
        md.write('- ファミコンの行（基板名あり）は **%d 行**で、未登録のマッパーを使う行は **%d 行**。基板名のないファミコンの行（%d 行、海賊版・マルチカートの番号が中心）は集計に入れていない。\n' % (len(fam), fam_unreg, fam_noboard))
        md.write('\n## 機能面の未対応・制限（ファミコンのライセンス品）\n\n')
        md.write('2026-11 の網羅性レビューによる。行数は上と同じ DB の行。\n\n')
        md.write('| 項目 | 対象 | 状態 |\n|---|---|---|\n')
        md.write('| バッテリーバックアップの保存 | 電池フラグのある %d 行 | RAM としては動くが、電源を切ると消える。rev G でハブ（U6）のフラッシュに保存する（未実装） |\n' % fam_batt)
        md.write('| PRG 512 KB／CHR 512 KB | %d 行／%d 行 | 1 個の RP2350（RAM 520 KB）に収まらない。rev G の増設 Pico 2（U4・U5）が要る |\n' % (fam_prg512, fam_chr512))
        md.write('| 音声合成チップ（μPD7755C／7756C、M50805） | %d 行（マッパー 3・18・72・86・92 の一部） | ゲームは動くが音声は出ない。音声データはチップの中にあり、ROM イメージに含まれない |\n' % fam_speech)
        md.write('| Datach のバーコード | マッパー 157 | 起動するが、カードを読ませる手段がない（常に「カードなし」） |\n')
        md.write('| カラオケスタジオのマイク | マッパー 188 | マイク入力なし。rev G は予備の入力（J4）を持つが、ファームは未実装 |\n')
        md.write('| ディスクシステム | DB に行なし | 未対応（RAM アダプタとドライブの再現が要る。BIOS は利用者が用意するもの） |\n')
        md.write('| コナミ QTa アダプタ（マッパー 547） | DB では NES 扱いの 8 行 | 未登録（ライセンスの扱いは未確認） |\n')
        md.write('| Study Box のテープ | マッパー 186 | 未対応 |\n')
        md.write('| MMC5 の PCM 読み出しモードとその IRQ | マッパー 5 | 未実装（使うライセンス品があるかは未確認） |\n')
        md.write('| Namco 163 で本体のネームテーブル RAM をパターンとして使う設定 | マッパー 19 | カートリッジ側の RAM で代用 |\n')
        md.write('\n修正済み（2026-11-10、`test/tm_ram.c`）: MMC5 の PRG-RAM（書き込み、チップ選択、$5130 の取り込み、ExRAM ネームテーブル）、VRC2／VRC4 と Namco 163 の RAM 書き込み、Taito X1-005 の内蔵 RAM、サンソフト 4 のサブカセット（なんてったって!! ベースボール）、サブマッパー 2 のバス競合。\n')
    print('romdb entries:', len(uniq), ' licensed:', total, ' covered: %.2f%%' % (100.0 * covered / total))

if __name__ == '__main__':
    main()
