def check(cond, what):
    print(('  ok    ' if cond else '  FAIL  ') + what)
    if not cond: FAILS.append(what)

def close(a, b, tol=1e-9):
    """numeric equality of nested lists / tuples / dicts of numbers and strings"""
    if isinstance(a, dict): return isinstance(b, dict) and set(a) == set(b) and all(close(a[k], b[k], tol) for k in a)
    if isinstance(a, (list, tuple)): return isinstance(b, (list, tuple)) and len(a) == len(b) and all(close(x, y, tol) for x, y in zip(a, b))
    if isinstance(a, float) or isinstance(b, float): return abs(a - b) <= tol
    return a == b

