def test_units():
    print('helpers')
    import gen_pcb, make_rails
    legacy = {2: {'F.Cu': [('GND', 'board')], 'B.Cu': [('GND', 'board')]}, 4: {'In1.Cu': [('GND', 'board')], 'In2.Cu': [('+3V3', 'board')]},
              6: {'In1.Cu': [('GND', 'board')], 'In4.Cu': [('+3V3', 'board')]}}
    check(all(gen_pcb.plane_map(n) == legacy[n] for n in (2, 4, 6)), 'plane_map() without PLANES / OUTER_GND = the pours used up to rev G (2, 4, 6 layers)')
    check(gen_pcb.plane_map(6, None, True) == dict(legacy[6], **{'F.Cu': [('GND', 'board')], 'B.Cu': [('GND', 'board')]}), 'OUTER_GND adds F/B GND')
    check(gen_pcb.plane_map(2, None, False) == {}, 'OUTER_GND False on 2 layers: no pour')
    p = {'In2.Cu': [('+3V3', 'board')], 'F.Cu': [('+5V', [(0, 0), (1, 0), (1, 1)])]}
    check(gen_pcb.plane_map(6, p, True) == {'In2.Cu': [('+3V3', 'board')], 'F.Cu': [('+5V', [(0, 0), (1, 0), (1, 1)])], 'B.Cu': [('GND', 'board')]},
          'PLANES replaces the default; OUTER_GND does not override a layer PLANES names')
    check(make_rails.fab_layers(2) == 'F.Cu,B.Cu,F.Paste,B.Paste,F.SilkS,B.SilkS,F.Mask,B.Mask,Edge.Cuts', 'fab_layers(2) = the list used up to rev G')
    check(make_rails.fab_layers(6).startswith('F.Cu,In1.Cu,In2.Cu,In3.Cu,In4.Cu,B.Cu,'), 'fab_layers(6) plots the inner layers')
    check(make_rails.top_tabs_clear((10.0, 45.0), 5.2, [('J3', 39.68, 50.32)], 1.0) == [(45.0, 'J3')], 'top_tabs_clear finds a tab in front of a connector')
    # via grid turned with the pad
    fp = pcbnew.FootprintLoad(PRETTY, 'QFN-80-1EP_10x10mm_P0.4mm_EP3.4x3.4mm_NoVia'); fp.SetPosition(pcbnew.VECTOR2I(FromMM(10), FromMM(20))); fp.SetOrientationDegrees(45)
    ep = [q for q in fp.Pads() if q.GetNumber() == '81'][0]
    pts = gen_pcb.ep_via_points(ep, 3, 1.1)
    r = sorted(round(math.hypot(x - 10, y - 20), 4) for x, y in pts)
    check(len(pts) == 9 and r == sorted([0.0] + [1.1] * 4 + [round(1.1 * math.sqrt(2), 4)] * 4) and any(abs(x - 10) < 1e-6 and abs(y - 20 + 1.5556) < 1e-3 for x, y in pts),
          'ep_via_points: grid centred on the pad and turned with it (45 deg: a corner via straight above the centre)')

