def run(tool, design, hw, tmp, expect=0):
    env = dict(os.environ, FC_DESIGN=design, FC_HW_DIR=hw, PYTHONPATH=tmp + os.pathsep + os.environ.get('PYTHONPATH', ''))
    r = subprocess.run([sys.executable, os.path.join(TOOLS, tool)], env=env, cwd=TOOLS, capture_output=True, text=True)
    out = r.stdout + r.stderr
    if (r.returncode == 0) != (expect == 0):
        print('    --- %s output (exit %d) ---\n%s' % (tool, r.returncode, textwrap.indent(out.strip()[-3000:], '    ')))
    return r.returncode, out

