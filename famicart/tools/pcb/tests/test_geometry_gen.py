def test_shells():
    print('shells.mirrored')
    cases = [('hvc_large(75, relief 0.6, side_inset 0.2)', shells.hvc_large(75.0, relief=0.6, side_inset=0.2)),
             ('hvc_large()', shells.hvc_large()), ('hvc_small()', shells.hvc_small()), ('rect_body(35.4)', shells.rect_body(35.4))]
    for name, s in cases:
        m = shells.mirrored(s); mm = shells.mirrored(m)
        check(close(mm, s), '%s: mirrored(mirrored(s)) == s numerically (%d keys)' % (name, len(s)))
        check(m['name'] == s['name'] + ' (mirrored)' and m.get('mirrored') is True and 'mirrored' not in mm, '%s: name / flag' % name)
        ok = all(abs(p[0] - (90 - q[0])) < 1e-9 and p[1] == q[1] for p, q in zip(m['outline_body'], reversed(s['outline_body'])))
        check(ok and close(m['outline_body'][0], (shells.TAB_X0, s['body_h'])) and close(m['outline_body'][-1], (shells.TAB_X1, s['body_h'])),
              '%s: outline x -> 90 - x, still from (TAB_X0, H) to (TAB_X1, H)' % name)
        check(all(sm == {'F': 'B', 'B': 'F'}[so] and close(pm, [(90 - x, y) for x, y in reversed(po)])
                  for (sm, pm), (so, po) in zip(m['comp_keepouts'], s['comp_keepouts'])), '%s: keep-outs mirrored, F <-> B' % name)
        check(all(close(pm, [(90 - x, y) for x, y in reversed(po)]) for k in ('cutouts', 'route_keepouts') for pm, po in zip(m[k], s[k])),
              '%s: cut-outs and routing keep-outs mirrored' % name)
        if 'fillets' in s: check(close(m['fillets'], [(90 - x, y) for x, y in s['fillets']]), '%s: fillet points mirrored' % name)
        for k in ('usb_top', 'edge_x'):
            if k in s: check(close(m[k], (90 - s[k][1], 90 - s[k][0])) and m[k][0] <= m[k][1], '%s: %s mirrored and ordered: %s' % (name, k, m[k]))
        # area and sense of rotation of the board outline are kept
        area = lambda p: sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(p, p[1:] + p[:1])) / 2
        check(abs(area(m['outline_body']) - area(s['outline_body'])) < 1e-6, '%s: outline area and orientation kept' % name)
    s = shells.hvc_large(75.0, relief=0.6, side_inset=0.2); m = shells.mirrored(s)
    posts = [p for side, p in m['comp_keepouts'] if side == 'F']
    check(sorted(round((min(x for x, _ in p) + max(x for x, _ in p)) / 2, 3) for p in posts) == [13.25, 76.75],
          'mirrored large shell: the two back posts (x\' -+31.75) are KiCad-F keep-outs at x 13.25 / 76.75')
    try: shells.mirrored(dict(s, new_geometry=[(1, 2)])); check(False, 'unknown keys are refused')
    except ValueError: check(True, 'unknown keys are refused')
    check(shells.hvc_large(75.0, relief=0.6, side_inset=0.2) == s, 'hvc_large() itself unchanged by mirroring (no aliasing)')

# ------------------------------------------------------------------------------------------------ footprints
def pads_of(name):
    fp = pcbnew.FootprintLoad(PRETTY, name)
    assert fp is not None, name
    out = []
    for p in fp.Pads():
        ls = p.GetLayerSet()
        cu = 'F' if ls.Contains(pcbnew.F_Cu) and not ls.Contains(pcbnew.B_Cu) else 'B' if ls.Contains(pcbnew.B_Cu) and not ls.Contains(pcbnew.F_Cu) else 'FB' if ls.Contains(pcbnew.F_Cu) else '-'
        mask = 'F' if ls.Contains(pcbnew.F_Mask) and not ls.Contains(pcbnew.B_Mask) else 'B' if ls.Contains(pcbnew.B_Mask) and not ls.Contains(pcbnew.F_Mask) else 'FB' if ls.Contains(pcbnew.F_Mask) else '-'
        out.append(dict(num=p.GetNumber(), x=ToMM(p.GetPosition().x), y=ToMM(p.GetPosition().y), w=ToMM(p.GetSize().x), h=ToMM(p.GetSize().y),
                        cu=cu, mask=mask, attr=p.GetAttribute(), drill=ToMM(p.GetDrillSize().x), paste=ls.Contains(pcbnew.F_Paste),
                        margin=ToMM(p.GetLocalSolderMaskMargin()), shape=p.GetShape()))
    return fp, out

def test_card_edge():
    print('Famicom_CardEdge_60_M against Famicom_CardEdge_60')
    _, o = pads_of('Famicom_CardEdge_60'); fpm, m = pads_of('Famicom_CardEdge_60_M')
    O = {p['num']: p for p in o}; M = {p['num']: p for p in m}
    check(sorted(O, key=int) == sorted(M, key=int) == [str(i) for i in range(1, 61)], 'pins 1-60, once each')
    swap = {'F': 'B', 'B': 'F'}
    bad = [n for n in O if not (abs(M[n]['x'] + O[n]['x']) < 1e-6 and abs(M[n]['y'] - O[n]['y']) < 1e-6 and M[n]['w'] == O[n]['w'] and M[n]['h'] == O[n]['h']
                                and M[n]['cu'] == swap[O[n]['cu']] and M[n]['mask'] == swap[O[n]['mask']] and M[n]['margin'] == O[n]['margin'] and M[n]['shape'] == O[n]['shape'])]
    check(not bad, 'every pad: x -> -x, same y, same size / shape / mask margin, copper and mask on the other side' + (' (bad: %s)' % bad if bad else ''))
    check(all(M[str(n)]['cu'] == 'F' for n in range(31, 61)) and all(M[str(n)]['cu'] == 'B' for n in range(1, 31)), 'pins 31-60 on F.Cu, pins 1-30 on B.Cu')
    # pin N+30 directly behind pin N (overlapping in x; centres at most 0.5 mm apart as in the original: pin 60 / 30)
    beh = [n for n in range(1, 31) if not (abs(M[str(n + 30)]['x'] - M[str(n)]['x']) <= 0.5 + 1e-6 and
                                          min(M[str(n)]['x'] + M[str(n)]['w'] / 2, M[str(n + 30)]['x'] + M[str(n + 30)]['w'] / 2) -
                                          max(M[str(n)]['x'] - M[str(n)]['w'] / 2, M[str(n + 30)]['x'] - M[str(n + 30)]['w'] / 2) > 1.0)]
    check(not beh, 'pin N+30 directly behind pin N' + (' (not: %s)' % beh if beh else ''))
    sizes = {n: (M[n]['w'], M[n]['h']) for n in ('1', '16', '30', '31', '46', '60', '2')}
    check(sizes == {'1': (2.6, 6.7), '16': (1.6, 6.7), '30': (2.6, 6.7), '31': (2.6, 6.7), '46': (1.6, 5.7), '60': (1.6, 5.7), '2': (1.6, 5.7)},
          'special pads keep their sizes: %s' % sizes)
    check(abs(M['31']['x'] - 37.33) < 1e-6 and abs(M['1']['x'] - 37.33) < 1e-6 and abs(M['60']['x'] + 36.83) < 1e-6 and abs(M['30']['x'] + 37.33) < 1e-6,
          'seen from the back: pin 31 (and 1 behind it) at the right end, pin 60 / 30 at the left end')
    # physically the same copper: original placed at (45, H) on a board drawn from the front, mirrored one at (45, H) on
    # the same board drawn from the back -> board x 45 + x_o (front view) == 90 - (45 + x_m), on the other KiCad side
    phys = all(abs((45 + O[n]['x']) - (90 - (45 + M[n]['x']))) < 1e-6 for n in O)
    check(phys, 'same physical finger positions (front view) as the original')
    check(fpm.GetFPID().GetLibItemName() == 'Famicom_CardEdge_60_M' and 'CardEdge' in 'Famicom_CardEdge_60_M', 'name contains "CardEdge" (gen_pcb / check_place / dsn_export treat it as the card edge)')

def test_qfn():
    print('QFN-80 _NoVia against the original')
    _, o = pads_of('QFN-80-1EP_10x10mm_P0.4mm_EP3.4x3.4mm'); _, n = pads_of('QFN-80-1EP_10x10mm_P0.4mm_EP3.4x3.4mm_NoVia')
    holes = [p for p in o if p['attr'] == pcbnew.PAD_ATTRIB_PTH]
    check(len(holes) == 9 and all(p['num'] == '81' for p in holes), 'the original has nine plated holes "81" in the exposed pad')
    key = lambda p: (p['num'], round(p['x'], 4), round(p['y'], 4), p['w'], p['h'], p['cu'], p['paste'], p['attr'])
    check(sorted(map(key, n)) == sorted(key(p) for p in o if p['attr'] != pcbnew.PAD_ATTRIB_PTH), 'everything else unchanged (pads 1-80, exposed pad, paste windows)')
    check(not any(p['drill'] > 0 for p in n), 'no holes left')
    numbered = [p for p in n if p['num']]
    check(len(numbered) == 81 and sorted({p['num'] for p in numbered}, key=int) == [str(i) for i in range(1, 82)], '81 numbered pads (JLCPCB C42415655 has 81)')
    ep = [p for p in n if p['num'] == '81']
    check(len(ep) == 1 and (ep[0]['w'], ep[0]['h']) == (3.4, 3.4) and not ep[0]['paste'], 'exposed pad 3.4 x 3.4 mm, no paste of its own')
    check(len([p for p in n if not p['num'] and p['paste'] and p['cu'] == '-']) == 4, 'four paste windows on the exposed pad')

