def jlc_check_failures(out):
    return [l for l in out.splitlines() if l.startswith('  FAIL')]

def jlc_on_test_board(hw, tmp):
    """The package of the test board (fabrication files plotted here, gen_jlc.py without the parts API), then
    check_jlc.py: the board is not routed, so it fails, but nothing about the rails, tabs, holes, fiducials, tooling
    holes or the contour of the panel make_rails.py built with RAILS['top'] may fail."""
    fab = os.path.join(hw, 'fab'); os.makedirs(fab, exist_ok=True)
    pcb = os.path.join(hw, 'famicart.kicad_pcb')
    subprocess.run(['kicad-cli', 'pcb', 'export', 'gerbers', '--layers', 'F.Cu,In1.Cu,In2.Cu,In3.Cu,In4.Cu,B.Cu,F.Paste,B.Paste,F.SilkS,B.SilkS,F.Mask,B.Mask,Edge.Cuts', '-o', fab + '/', pcb], check=True, capture_output=True)
    subprocess.run(['kicad-cli', 'pcb', 'export', 'drill', '--format', 'excellon', '--excellon-separate-th', '-o', fab + '/', pcb], check=True, capture_output=True)
    open(os.path.join(tmp, 'run_gen_jlc.py'), 'w').write(RUN_GEN_JLC)
    env = dict(os.environ, FC_DESIGN='design_selftest_h', FC_HW_DIR=hw, FC_ALLOW_UNROUTED='1', PYTHONPATH=tmp + os.pathsep + TOOLS)
    r = subprocess.run([sys.executable, os.path.join(tmp, 'run_gen_jlc.py')], env=env, cwd=TOOLS, capture_output=True, text=True)
    check(r.returncode == 0, 'gen_jlc.py writes the package of the test board (exit %d)%s' % (r.returncode, '' if r.returncode == 0 else ': ' + (r.stdout + r.stderr)[-400:]))
    rc, out = run('check_jlc.py', 'design_selftest_h', hw, tmp, expect=1)
    fails = jlc_check_failures(out)
    words = ('rail', 'panel', 'tab ', 'tabs', 'break-off', 'fiducial', 'FID', 'tooling', 'contour', 'inside the rails', 'hole edge', 'mask opening')
    railish = [l for l in fails if any(w in l for w in words) and 'rails.svg' not in l and 'rails.png' not in l]
    check('with edge rails: panel 103.6 x 92.7 mm' in out and not railish, 'check_jlc accepts the panel with a top rail (no failure about rails, tabs, holes, fiducials, tooling holes, contour)%s'
          % ('' if not railish else ': ' + ' | '.join(railish[:4])))
    m = re.search(r'with edge rails: panel [^;]*; [^;]*; (\d+) tabs of ([\d.]+)\.\.([\d.]+) mm, material between break-off holes ([\d.]+)\.\.([\d.]+) mm; (\d+) fiducials, nearest ([\d.]+) mm from a panel edge; (\d+) tooling holes', out)
    check(m and m.group(1) == '10' and m.group(6) == '6' and m.group(8) == '4' and float(m.group(7)) >= 3.85 - 0.002,
          'check_jlc measured 10 tabs (3 + 3 side, 4 top), 6 fiducials (3 per side) at >= 3.85 mm, 4 tooling holes: %s' % ((m.groups() if m else None),))
    # a top-rail panel that check_jlc must refuse: a top tab hole pushed into the board
    br = pcbnew.LoadBoard(os.path.join(hw, 'famicart_rails.kicad_pcb'))
    mb = sorted((f for f in br.GetFootprints() if f.GetReference().startswith('MB') and ToMM(f.GetPosition().y) < 0), key=lambda f: f.GetReference())[0]
    mb.SetPosition(pcbnew.VECTOR2I(mb.GetPosition().x, FromMM(0.2)))
