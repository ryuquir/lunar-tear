#!/usr/bin/env python3
"""Build the rev D boot bank (8 KB, mapped at every CPU window until U1 takes over) with a tiny 6502 stub.

  RESET: SEI/CLD, disable PPU rendering, copy the trampoline to console RAM $0300, JMP $0300.
  $0300: wait until $5F00 == $A5 (U1 ready), then until $5F01 == 1 (go), then JMP ($FFFC) -- by then
         U1 has put the game's banks on the lines, so the vector fetched is the game's own reset vector.
  The stub never touches the cartridge again once it runs from RAM, so U1 may isolate the bus meanwhile.
Writes src/revd_prg/bootstub_gen.h."""
import os, struct

OPS = {'SEI': 0x78, 'CLD': 0xD8, 'TXS': 0x9A, 'INX': 0xE8, 'DEX': 0xCA, 'NOP': 0xEA, 'RTI': 0x40,
       'LDX#': 0xA2, 'LDA#': 0xA9, 'CMP#': 0xC9, 'STA': 0x8D, 'LDA': 0xAD, 'LDAx': 0xBD, 'STAx': 0x9D, 'BNE': 0xD0, 'BEQ': 0xF0, 'BPL': 0x10, 'JMP': 0x4C, 'JMPi': 0x6C, 'BIT': 0x2C}

class Asm:
    def __init__(self, org): self.org = org; self.b = bytearray(); self.labels = {}; self.fix = []
    @property
    def pc(self): return self.org + len(self.b)
    def label(self, n): self.labels[n] = self.pc
    def op(self, m, arg=None):
        self.b.append(OPS[m])
        if m.endswith('#'): self.b.append(arg & 0xFF)
        elif m in ('BNE', 'BEQ', 'BPL'): self.fix.append((len(self.b), arg)); self.b.append(0)
        elif m in ('STA', 'LDA', 'LDAx', 'STAx', 'JMP', 'JMPi', 'BIT'):
            if isinstance(arg, str): self.fix.append((len(self.b), arg, 'abs')); self.b += b'\0\0'
            else: self.b += struct.pack('<H', arg)
    def resolve(self):
        for f in self.fix:
            if len(f) == 2:
                off, lab = f; rel = self.labels[lab] - (self.org + off + 1); assert -128 <= rel < 128; self.b[off] = rel & 0xFF
            else:
                off, lab, _ = f; self.b[off:off + 2] = struct.pack('<H', self.labels[lab])
        return bytes(self.b)

# trampoline (runs at $0300)
t = Asm(0x0300)
t.label('wait_ready'); t.op('LDA', 0x5F00); t.op('CMP#', 0xA5); t.op('BNE', 'wait_ready')
t.label('wait_go');    t.op('LDA', 0x5F01); t.op('CMP#', 0x01); t.op('BNE', 'wait_go')
t.op('JMPi', 0xFFFC)
tramp = t.resolve()

# reset code (in the boot bank, mapped at $E000-$FFFF when fetched through the $E000 window)
BASE = 0xE000
r = Asm(BASE)
r.label('reset'); r.op('SEI'); r.op('CLD'); r.op('LDX#', 0xFF); r.op('TXS')
r.op('LDA#', 0x00); r.op('STA', 0x2000); r.op('STA', 0x2001)          # NMI off, rendering off
r.label('vw1'); r.op('BIT', 0x2002); r.op('BPL', 'vw1')                 # wait a vblank so the PPU is quiet
r.op('LDX#', 0x00)
r.label('copy'); r.op('LDAx', 'tramp'); r.op('STAx', 0x0300); r.op('INX'); r.op('CMP#', 0x00)   # (CMP only to keep flags; INX count below)
r.b[-2:] = b''                                                        # drop the CMP (placeholder removed)
r.op('LDA#', 0); r.b.pop(); r.b.pop()                                 # (no-op guard)
# simpler loop: X from 0 to len(tramp)-1
r.b = bytearray(); r.fix = []; r.labels = {}
r.label('reset'); r.op('SEI'); r.op('CLD'); r.op('LDX#', 0xFF); r.op('TXS')
r.op('LDA#', 0x00); r.op('STA', 0x2000); r.op('STA', 0x2001)
r.label('vw1'); r.op('BIT', 0x2002); r.op('BPL', 'vw1')
r.op('LDX#', len(tramp) - 1)
r.label('copy'); r.op('LDAx', 'tramp'); r.op('STAx', 0x0300); r.op('DEX'); r.op('BPL', 'copy')
r.op('JMP', 0x0300)
r.label('irq'); r.op('RTI')
r.label('tramp'); r.b += tramp
code = r.resolve()

bank = bytearray(b'\xFF' * 8192)
bank[0:len(code)] = code
# vectors at $FFFA-$FFFF (= offsets $1FFA-$1FFF of the 8 KB bank); NMI/IRQ -> RTI, RESET -> reset
nmi = r.labels['irq']; rst = r.labels['reset']; irq = r.labels['irq']
bank[0x1FFA:0x2000] = struct.pack('<HHH', nmi, rst, irq)
# identification string (also lets the host check that the boot bank is programmed)
bank[0x1F00:0x1F00 + 16] = b'FAMICART-BOOT-01'
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'revd_prg', 'bootstub_gen.h')
with open(out, 'w') as f:
    f.write('/* generated by tools/bootstub.py: 8 KB boot bank for the rev D PRG flash (top bank) */\n#pragma once\n#include <stdint.h>\n')
    f.write('#define BOOTSTUB_CODE_LEN %d\nstatic const uint8_t bootstub_bank[8192] = {\n' % len(code))
    for i in range(0, 8192, 32): f.write('  ' + ','.join('0x%02X' % b for b in bank[i:i + 32]) + ',\n')
    f.write('};\n')
print('boot stub: %d bytes of code, trampoline %d bytes -> %s' % (len(code), len(tramp), out))
print('disasm reset:', code[:40].hex())
